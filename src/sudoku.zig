pub fn Sudoku(comptime R: type) type {
    return struct {
        engine: game_engine.GameEngine,
        cfg: config.Config,
        io: std.Io,
        renderer: *R,
        pub fn init(cfg: config.Config, _r: *R, io: std.Io) anyerror!@This() {
            const puzzle_str = puzzle_gen.PuzzleGen.generate(cfg.difficulty);
            return @This(){
                .renderer = _r,
                .io = io,
                .cfg = cfg,
                .engine = try game_engine.GameEngine.init(puzzle_str, io),
            };
        }

        /// Read a line from stdin excluding newline at the end
        fn readLine(reader: anytype) anyerror![]const u8 {
            return try reader.takeDelimiter('\n') orelse return error.ReadEOF;
        }

        /// Show an error message and wait for Enter to continue.
        fn waitAck(self: *@This(), writer: anytype, reader: anytype, msg: []const u8) anyerror!void {
            _ = self;
            try writer.print("{s}\n", .{msg});
            try writer.print("Press Enter to continue... ", .{});

            _ = try readLine(reader);
        }

        /// Print the command legend line after a board render.
        fn printLegend(self: *@This(), writer: anytype) !void {
            const avail = self.engine.getAvailableCommands();

            var names: [8][]const u8 = undefined;
            const count = avail.getNames(&names);

            var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
            defer arena.deinit();

            const entries = try disambiguate.getMinimumPrefixes(arena.allocator(), names[0..count]);
            const str = try legend.formatLegend(arena.allocator(), entries);

            try writer.print("  Command: {s}\n", .{str});
        }

        /// Handle a dispatched Event. Returns true when is_quit flag is set.
        /// (the 'isDone' signal is only generated by handleResult — e.g. .quit).
        fn handleEvent(self: *@This(), out: anytype, in_: anytype, event: game_engine.Event) anyerror!bool {
            switch (event) {
                .ok => |ev| {
                    if (ev.is_quit) return true;

                    if (ev.msg) |m| try out.print("{s}\n", .{m});
                    try self.renderer.render(ev.board_view, null);
                    try self.printLegend(out);
                    return false;
                },
                .error_msg => |msg| {
                    try self.waitAck(out, in_, msg);
                    return false;
                },
            }
        }

        /// Handle one parsed result. Returns true when the command loop should end.
        fn handleResult(self: *@This(), out: anytype, in_: anytype, result: command.ParseCommandResult) anyerror!bool {
            switch (result) {
                .error_msg => |msg| {
                    try self.waitAck(out, in_, msg);
                    return false;
                },
                .valid => |cmd| {
                    const event = self.engine.exec(cmd) catch |err| {
                        var buf: [80]u8 = undefined;
                        const msg = std.fmt.bufPrint(&buf, "exec failed: {s}", .{@errorName(err)}) catch unreachable;
                        try self.waitAck(out, in_, msg);
                        return false;
                    };
                    return self.handleEvent(out, in_, event) catch |err| {
                        var buf: [80]u8 = undefined;
                        const msg = std.fmt.bufPrint(&buf, "handleEvent failed: {s}", .{@errorName(err)}) catch unreachable;
                        try self.waitAck(out, in_, msg);
                        return false;
                    };
                },
            }
        }

        /// Prompt the user, read a line, parse it, and dispatch. Returns true on quit.
        fn promptForAndRunCommand(self: *@This(), out: anytype, in_: anytype) anyerror!bool {
            try out.print("> ", .{});

            const line = try readLine(in_);
            if (line.len == 0) return false; // empty input -> stay in loop

            const tokens = std.mem.trim(u8, line, &std.ascii.whitespace);
            // Build available command names for context-aware prefix dispatch
            const avail = self.engine.getAvailableCommands();

            var names: [8][]const u8 = undefined;
            const count = avail.getNames(&names);

            const result = command.parseWithCommands(tokens, names[0..count]);

            // First save: prompt for a filename.
            switch (result) {
                .valid => |cmd| {
                    switch (cmd) {
                        .save => {
                            if (self.engine.filename == null) {
                                const gpa = std.heap.page_allocator;

                                // Resolve data dir first so we can show the full default path.
                                if (self.engine.data_dir == null) {
                                    self.engine.data_dir = try mypath.getDataDir(gpa, self.io);
                                }

                                const resolved_default = try mypath.resolveSavePath(
                                     gpa,
                                     self.engine.data_dir.?,
                                     ".sudoku_save.sud",
                                );
                                defer gpa.free(resolved_default);

                                try out.print("Save to [{s}]: ", .{resolved_default});

                                const save_input = try readLine(in_);
                                const trimmed = std.mem.trim(u8, save_input, &std.ascii.whitespace);
                                const chosen = if (trimmed.len > 0)
                                    trimmed
                                else
                                    ".sudoku_save.sud";
                                self.engine.filename = try gpa.dupe(u8, chosen);
                            }
                        },
                        else => {},
                    }
                    },
                .error_msg => {},
            }

            return try self.handleResult(out, in_, result);
        }

        /// Read → Parse → Loop command interface.
        pub fn run(self: *@This()) anyerror!void {
            var stdout_writer = std.Io.File.stdout().writer(self.io, &.{});
            const out = &stdout_writer.interface;
            var stdin_buf: [1024]u8 = undefined;
            var stdin_reader = std.Io.File.stdin().reader(self.io, &stdin_buf);
            const in_ = &stdin_reader.interface;

            // Initial render — show starting board via Event seam
            try self.renderer.render(self.engine.eventBoard(), null);
            try self.printLegend(out);

            var isDone: bool = false;
            while (!isDone) {
                isDone = try self.promptForAndRunCommand(out, in_);
            }
        }
    };
}

