const std = @import("std");
const game_engine = @import("game_engine.zig");
const config = @import("config.zig");
const puzzle_gen = @import("puzzle_gen.zig");
const command = @import("command.zig");

const disambiguate = @import("disambiguate.zig");
const legend = @import("legend.zig");
pub fn Sudoku(comptime R: type) type {
    return struct {
        engine: game_engine.GameEngine,
        cfg: config.Config,

        pub fn init(cfg: config.Config, _r: *R) anyerror!@This() {
            _ = _r; // not forwarded to engine anymore — renderer lives in run()
            const puzzle_str = puzzle_gen.PuzzleGen.generate(cfg.difficulty);
            const engine = try game_engine.GameEngine.init(puzzle_str);
            return .{
                .engine = engine,
                .cfg = cfg,
            };
        }

        /// Read a line from stdin excluding newline at the end
        fn readLine(reader: anytype) anyerror![]const u8 {
            return try reader.takeDelimiter('\n') orelse return error.ReadEOF;
        }

        /// Show an error message and wait for Enter to continue.
        fn waitAck(self: *@This(), writer: anytype, reader: anytype, msg: []const u8) anyerror!void {
            _ = self;
            try writer.print("{s}\n", .{msg});
            try writer.print("Press Enter to continue... ", .{});

            _ = try readLine(reader);
        }

        /// Print the command legend line after a board render.
        fn printLegend(self: *@This(), writer: anytype) !void {
            const avail = self.engine.getAvailableCommands();

            var names: [5][]const u8 = undefined;
            var count: usize = 0;
            if (avail.fill) { names[count] = "Fill"; count += 1; }
            if (avail.clear) { names[count] = "Clear"; count += 1; }
            if (avail.quit) { names[count] = "Quit"; count += 1; }
            if (avail.undo) { names[count] = "Undo"; count += 1; }
            if (avail.redo) { names[count] = "Redo"; count += 1; }

            var arena = std.heap.ArenaAllocator.init(std.heap.page_allocator);
            defer arena.deinit();

            const entries = try disambiguate.getMinimumPrefixes(arena.allocator(), names[0..count]);
            const str = try legend.formatLegend(arena.allocator(), entries);

            try writer.print("  Command: {s}\n", .{str});
        }

        /// Handle a dispatched Event. Always returns false to keep the loop going
        /// (the 'isDone' signal is only generated by handleResult — e.g. .quit).
        fn handleEvent(self: *@This(), out: anytype, in_: anytype, renderer: anytype, event: game_engine.Event) anyerror!bool {
            switch (event) {
                .ok => |ev| {
                    if (ev.msg) |m| try out.print("{s}\n", .{m});
                    try renderer.render(ev.board_view);
                    try self.printLegend(out);
                    return false;
                },
                .error_msg => |msg| {
                    try self.waitAck(out, in_, msg);
                    return false;
                },
            }
        }

        /// Handle one parsed result. Returns true when the command loop should end.
        fn handleResult(self: *@This(), out: anytype, in_: anytype, renderer: anytype, result: command.ParseCommandResult) anyerror!bool {
            switch (result) {
                .error_msg => |msg| {
                    try self.waitAck(out, in_, msg);
                    return false; // continue looping
                },
                .valid => |cmd| {
                    if (cmd == .quit) return true;

                    const event = try self.engine.exec(cmd);
                    return try self.handleEvent(out, in_, renderer, event);
                },
            }
        }

        /// Prompt the user, read a line, parse it, and dispatch. Returns true on quit.
        fn promptForAndRunCommand(self: *@This(), out: anytype, in_: anytype, renderer: anytype) anyerror!bool {
            try out.print("> ", .{});

            const line = try readLine(in_);
            if (line.len == 0) return false; // empty input -> stay in loop

            const tokens = std.mem.trim(u8, line, &std.ascii.whitespace);

            // Build available command names for context-aware prefix dispatch
            const avail = self.engine.getAvailableCommands();
            var names: [5][]const u8 = undefined;
            var count: usize = 0;
            if (avail.fill) { names[count] = "Fill"; count += 1; }
            if (avail.clear) { names[count] = "Clear"; count += 1; }
            if (avail.quit) { names[count] = "Quit"; count += 1; }
            if (avail.undo) { names[count] = "Undo"; count += 1; }
            if (avail.redo) { names[count] = "Redo"; count += 1; }

            const result = command.parseWithCommands(tokens, names[0..count]);
            return try self.handleResult(out, in_, renderer, result);
        }

        /// Read → Parse → Loop command interface.
        pub fn run(self: *@This(), io: std.Io, renderer: anytype) anyerror!void {
            var stdout_writer = std.Io.File.stdout().writer(io, &.{});
            const out = &stdout_writer.interface;
            var stdin_buf: [1024]u8 = undefined;
            var stdin_reader = std.Io.File.stdin().reader(io, &stdin_buf);
            const in_ = &stdin_reader.interface;

            // Initial render — show starting board via Event seam
            try renderer.render(self.engine.eventBoard());
            try self.printLegend(out);

            var isDone: bool = false;
            while (!isDone) {
                isDone = try self.promptForAndRunCommand(out, in_, renderer);
            }
        }
    };
}

