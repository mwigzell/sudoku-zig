const MockReader = struct {
    responses: []const []const u8,
    idx: usize,

    pub fn initMockReader(responses: []const []const u8) MockReader {
        return .{
            .responses = responses,
            .idx = 0,
        };
    }

    /// Match Io.Reader.interface.takeDelimiter signature: !?[]u8
    pub fn takeDelimiter(self: *MockReader, delimiter: u8) !?[]u8 {
        _ = delimiter;
        if (self.idx >= self.responses.len) return null;
        const resp = self.responses[self.idx];
        return @constCast(resp);
    }
};

const MockWriter = struct {
    buffer: [2048]u8,
    pos: usize,

    pub fn initMockWriter() MockWriter {
        var buf: [2048]u8 = undefined;
        @memset(&buf, 0);
        return .{
            .buffer = buf,
            .pos = 0,
        };
    }

    pub fn getWritten(self: *const MockWriter) []const u8 {
        return self.buffer[0..self.pos];
    }

    pub fn print(self: *MockWriter, comptime fmt: []const u8, args: anytype) !void {
        const written = try std.fmt.bufPrint(self.buffer[self.pos..], fmt, args);
        self.pos += written.len;
    }
};


