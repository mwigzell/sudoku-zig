test "legend pipeline: after fill then undo shows Undo AND Redo" {
    var engine = try game_engine.GameEngine.init(puzzle_gen.PuzzleGen.default());
    defer engine.deinit();

    // Fill a cell to enable Undo
    _ = try engine.exec(command.Command{
        .fill = command.FillData{ .row = 0, .col = 2, .digit = cell.CellValue.seven },
    });

    // Undo to populate both Undo and Redo availability... wait — after undo only Redo.
    // Let me test: fill TWO cells, undo ONE → both Undo AND Redo available.
    _ = try engine.exec(command.Command{
        .fill = command.FillData{ .row = 0, .col = 3, .digit = cell.CellValue.one },
    });

    // Now undo once — pointer goes from 2 to 1
    _ = try engine.exec(command.Command{ .undo = {} });

    const avail = engine.getAvailableCommands();
    try std.testing.expect(avail.fill);
    try std.testing.expect(avail.clear);
    try std.testing.expect(avail.quit);
    try std.testing.expect(avail.undo);
    try std.testing.expect(avail.redo);

    var names: [5][]const u8 = undefined;
    var count: usize = 0;
    if (avail.fill) { names[count] = "Fill"; count += 1; }
    if (avail.clear) { names[count] = "Clear"; count += 1; }
    if (avail.quit) { names[count] = "Quit"; count += 1; }
    if (avail.undo) { names[count] = "Undo"; count += 1; }
    if (avail.redo) { names[count] = "Redo"; count += 1; }

    const entries = try disambiguate.getMinimumPrefixes(std.testing.allocator, names[0..count]);
    defer std.testing.allocator.free(entries);

    const result = try legend.formatLegend(std.testing.allocator, entries);
    defer std.testing.allocator.free(result);

    // With all 5 commands, each prefix is 1 char (F/C/Q/U/R all distinct)
    try std.testing.expectEqualStrings("(F)ill (C)lear (Q)uit (U)ndo (R)edo", result);
}

// Step 11 — mock I/O for full-seam integration test through promptForAndRunCommand.

const MockReader = struct {
    responses: []const []const u8,
    idx: usize,

    pub fn initMockReader(responses: []const []const u8) MockReader {
        return .{
            .responses = responses,
            .idx = 0,
        };
    }

    /// Match Io.Reader.interface.takeDelimiter signature: !?[]u8
    pub fn takeDelimiter(self: *MockReader, delimiter: u8) !?[]u8 {
        _ = delimiter;
        if (self.idx >= self.responses.len) return null;
        const resp = self.responses[self.idx];
        return @constCast(resp);
    }
};

const MockWriter = struct {
    buffer: [2048]u8,
    pos: usize,

    pub fn initMockWriter() MockWriter {
        var buf: [2048]u8 = undefined;
        @memset(&buf, 0);
        return .{
            .buffer = buf,
            .pos = 0,
        };
    }

    pub fn getWritten(self: *const MockWriter) []const u8 {
        return self.buffer[0..self.pos];
    }

    pub fn print(self: *MockWriter, comptime fmt: []const u8, args: anytype) !void {
        const written = try std.fmt.bufPrint(self.buffer[self.pos..], fmt, args);
        self.pos += written.len;
    }
};

test "full seam: f A3 4 -> prefix dispatch -> fill (0,2)=four -> render+legend w/ Undo" {
    // Arrange: fresh engine via Sudoku.init gives Fill/Clear/Quit only.
    const cfg: config.Config = .{
        .difficulty = .hard,
        .preferred_renderer = .ascii_ansi,
        .fallback_renderer = .ascii_ansi,
    };
    var mock = mock_renderer.MockRenderer.init();
    var sudoku = try Sudoku(mock_renderer.MockRenderer).init(cfg, &mock);
    defer sudoku.engine.deinit();

    // Feed: "f A3 4" as the single typed command.
    var mr = MockReader.initMockReader(&[_][]const u8{ "f A3 4" });
    var mw = MockWriter.initMockWriter();

    // Act: one cycle of prompt -> parse -> dispatch -> exec -> render -> legend
    _ = try sudoku.promptForAndRunCommand(&mw, &mr, &mock);

    // Assert (a): engine has undo available after mutation.
    {
        const avail = sudoku.engine.getAvailableCommands();
        try std.testing.expect(avail.undo);
    }

    // Assert (b): renderer was called, cell at chess coord A3 -> row 2, col 0 is four.
    {
        try std.testing.expect(mock.call_count > 0);
        const rendered = mock.last_rendered_cells orelse unreachable;
        try std.testing.expectEqual(cell.CellValue.four, rendered[2][0]);
    }

    // DEBUG: print mock writer output so we can see what's missing
    // Assert (c): legend shows Undo available now that a mutation occurred.
    {
        const output = mw.getWritten();
        try std.testing.expect(std.mem.indexOf(u8, output, "Command:") != null);
        // Legend formats as "(U)ndo" not plain "Undo" — search formatted form
        try std.testing.expect(std.mem.indexOf(u8, output, "(U)ndo") != null);
    }
}
